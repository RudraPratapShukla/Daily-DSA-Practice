package Operators;

public class relational {
    public static void main(String[] args) {
        int a = 10;
        int b = 5;
        System.out.println(a == b); // to check if a,b are equal
        System.out.println(a != b); // to check if a,b are not equal
        System.out.println(a > b); // to check if a is greater than b
        System.out.println(a < b); // to check if a is less than b
        System.out.println(a >= b); // to check if a is greater than or equal to b
        System.out.println(a <= b); // to check if a is less than or equal to b
    }

}
