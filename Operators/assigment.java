package Operators;

public class assigment {
    public static void main(String[] args) {
        int a = 10;
        a += 5;
        System.out.println(a); // a=a+5
        int b = 5;
        b -= 5;
        System.out.println(b); // b=b-5
        int c = 5;
        c *= 5;
        System.out.println(c); // c=c*5
        int d = 5;
        d /= 5;
        System.out.println(d); // d=d/5
        int e = 5;
        e %= 5;
        System.out.println(e); // e=e%5
    }

}
